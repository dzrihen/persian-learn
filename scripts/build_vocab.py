"""Build Modern Persian (fa-IR) lemma bank with Hebrew glosses → vocab_entries.py"""
import re, pathlib
BANK = []
seen = set()

FA_RE = re.compile(r"[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]")

def add(lem, he, pos, theme, cefr):
    lem = (lem or "").strip()
    he = (he or "").strip()
    if not lem or not he: return
    if lem in seen: return
    if not FA_RE.search(lem): return
    if re.search(r"[A-Za-zА-Яа-яΑ-Ωα-ω]", lem): return
    seen.add(lem)
    BANK.append((lem, he, pos, theme, cefr))

def bulk(rows, theme, cefr, pos=None):
    for r in rows:
        if len(r) == 2:
            w, h = r; p = pos or "n"
        elif len(r) == 3:
            w, h, p = r
        elif len(r) == 4:
            w, h, p, c = r; add(w, h, p, theme, c); continue
        else:
            continue
        add(w, h, p, theme, cefr)

